// Outlines the text of the Open Graph card into src/og-glyphs.ts, so the card renders the same everywhere without
// web fonts. resvg (scripts/gen-og.mjs) cannot turn on OpenType features, and the card needs Beast's ss01 A and D,
// the glyphs the site shows. Re-run after changing any text below, then run `npm run og`.
//
// Usage: npm run og:glyphs
import * as fontkit from 'fontkit';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const beast = fontkit.openSync(join(root, 'public/fonts/Beast-Regular.woff2'));
const courneuf = fontkit.openSync(join(root, 'public/fonts/Courneuf-Regular.ttf'));
const mono = fontkit.openSync(join(root, 'public/fonts/JetBrainsMono-Medium.woff2'));

// The card asks the MCP server about a post: the hub, the seven tools on its fan, the question, and the four counts the
// backlinks tool returned. The same tracking the site uses: Beast figures at -0.04em, the hub at -0.02em.
const TOOLS = ['resolve', 'get', 'list_records', 'backlinks', 'discover', 'lexicon', 'labels'];
const FIGURES = [
	['2,074', 'likes'],
	['790', 'replies'],
	['1,092', 'quotes'],
	['350', 'reposts'],
];
const RUNS = {
	hub: [beast, 'atproto.md/mcp', -0.02, ['ss01', 'cv11']],
	question: [mono, 'Who replied to this post, and how many liked it?', 0, []],
	...Object.fromEntries(TOOLS.map((t) => [t, [courneuf, t, 0, []]])),
	...Object.fromEntries(
		FIGURES.flatMap(([n, l]) => [
			[n, [beast, n, -0.04, ['ss01', 'cv11']]],
			[l, [mono, l, 0, []]],
		]),
	),
};

const round = (d) => d.replace(/-?\d+\.\d+/g, (m) => String(Math.round(+m)));
const out = {};
for (const [key, [font, text, tracking, features]] of Object.entries(RUNS)) {
	const run = font.layout(text, features);
	let x = 0;
	let d = '';
	run.glyphs.forEach((g, i) => {
		d += g.path.scale(1, -1).translate(x, 0).toSVG();
		x += run.positions[i].xAdvance + (i < run.glyphs.length - 1 ? tracking * font.unitsPerEm : 0);
	});
	// Baseline at y 0, in font units. width is the advance of the whole run, for centering. asc and desc are the
	// font's ascent and descent, so a baseline can be placed in a line box the way a browser places it.
	out[key] = { upm: font.unitsPerEm, asc: font.ascent, desc: font.descent, width: Math.round(x), d: round(d) };
}

const file = `// Generated by scripts/og-glyphs.mjs from public/fonts. Do not edit by hand.
// Text runs of the Open Graph card as outlines: baseline at y 0, in font units (upm), width is the run's advance.
export const TOOLS: string[] = ${JSON.stringify(TOOLS)};
export const FIGURES: [string, string][] = ${JSON.stringify(FIGURES)};
export const OG_GLYPHS: Record<string, { upm: number; asc: number; desc: number; width: number; d: string }> = ${JSON.stringify(out, null, '\t')};
`;
writeFileSync(join(root, 'src/og-glyphs.ts'), file);
console.log(`wrote src/og-glyphs.ts (${Object.keys(out).length} runs)`);
