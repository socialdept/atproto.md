// Builds the list of known labelers into src/labelers.ts: every account on the network with an
// app.bsky.labeler.service record, ranked by how many people like (subscribe to) it, the top ones kept.
// Review the result before committing: drop any that are not meant for general use. Run: npm run labelers
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const RELAY = 'https://relay1.us-west.bsky.network';
const APPVIEW = 'https://public.api.bsky.app';
const KEEP = Number(process.argv[2] ?? 20);
// Bluesky's own moderation labeler is the default for every labels lookup, so it always stays on the list.
const DEFAULT = 'did:plc:ar7c4by46qjdydhdevvrndac';

async function json(url) {
	const res = await fetch(url, { headers: { Accept: 'application/json' } });
	if (!res.ok) throw new Error(`${url} answered ${res.status}`);
	return res.json();
}

// Every DID with a labeler service record.
const dids = [];
let cursor;
do {
	const url = new URL(`${RELAY}/xrpc/com.atproto.sync.listReposByCollection`);
	url.searchParams.set('collection', 'app.bsky.labeler.service');
	url.searchParams.set('limit', '2000');
	if (cursor) url.searchParams.set('cursor', cursor);
	const page = await json(url);
	dids.push(...page.repos.map((r) => r.did));
	cursor = page.cursor;
} while (cursor);

// Their like counts and handles from the app view, 25 at a time.
const views = [];
for (let i = 0; i < dids.length; i += 25) {
	const url = new URL(`${APPVIEW}/xrpc/app.bsky.labeler.getServices`);
	for (const did of dids.slice(i, i + 25)) url.searchParams.append('dids', did);
	url.searchParams.set('detailed', 'true');
	try {
		views.push(...(await json(url)).views);
	} catch {}
}

const usable = views.filter((v) => v.creator?.handle && v.creator.handle !== 'handle.invalid');
const ranked = usable.sort((a, b) => (b.likeCount ?? 0) - (a.likeCount ?? 0));
const kept = ranked.slice(0, KEEP);
if (!kept.some((v) => v.creator.did === DEFAULT)) {
	const fallback = ranked.find((v) => v.creator.did === DEFAULT);
	if (fallback) kept.unshift(fallback);
}

const line = (s) => String(s ?? '').replace(/\s+/g, ' ').trim().slice(0, 140);
const entries = kept.map((v) => ({ did: v.creator.did, handle: v.creator.handle, name: line(v.creator.displayName) || v.creator.handle, likes: v.likeCount ?? 0 }));

const file = `// Generated by scripts/labelers.mjs from the network's app.bsky.labeler.service records, ranked by likes.
// Reviewed by hand before committing. Re-run with: npm run labelers
export interface KnownLabeler {
	did: string;
	handle: string;
	name: string;
}

/** Bluesky's moderation labeler, used when a lookup names no labelers. */
export const DEFAULT_LABELER = '${DEFAULT}';

export const LABELERS: KnownLabeler[] = ${JSON.stringify(
	entries.map(({ likes, ...e }) => e),
	null,
	'\t',
)};
`;
writeFileSync(join(root, 'src/labelers.ts'), file);
console.log(`${dids.length} labelers on the network, ${views.length} with an app view, kept ${entries.length}:`);
for (const e of entries) console.log(`  ${String(e.likes).padStart(7)}  ${e.handle}  ${e.name}`);
